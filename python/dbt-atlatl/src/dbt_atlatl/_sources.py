"""dbt `sources:` for the tables atlatl lands in DuckDB files, from `atlatl plan --static`."""

from __future__ import annotations

import json
import os
import re
import subprocess
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from dbt_atlatl._run import AtlatlRunError, binary_path

HEADER = "# Generated by `python -m dbt_atlatl sources` from the atlatl plan; do not edit.\n"
_MEMBER_VAR = re.compile(r"\{\{\s*member\.(name|schema|table)\s*\}\}")


@dataclass(frozen=True)
class Table:
    schema: str
    name: str
    replication: str
    stream: str
    asset_key: str
    mode: str
    description: str | None


def load_plan(
    project: Path, binary: str | None = None, env: Mapping[str, str] | None = None
) -> Mapping[str, Any]:
    cmd = [str(binary_path(binary)), "--project", str(project), "plan", "--static", "--json"]
    full_env = {**os.environ, **(env or {})}
    try:
        p = subprocess.run(
            cmd, capture_output=True, text=True, timeout=120, check=False, env=full_env
        )
    except (OSError, subprocess.SubprocessError) as e:
        raise AtlatlRunError(f"running `{' '.join(cmd)}` failed: {e}") from e
    if p.returncode != 0:
        raise AtlatlRunError(
            f"`atlatl plan --static` failed (exit {p.returncode}):\n{p.stderr.strip()}"
        )
    plan: Mapping[str, Any] = json.loads(p.stdout)
    return plan


def _split(obj: str) -> tuple[str, str]:
    parts = [p.strip('"') for p in obj.split(".")]
    # A three-part name's catalog is atlatl's attach alias, which means nothing to dbt.
    if len(parts) == 3:
        parts = parts[1:]
    if len(parts) == 1:
        return "main", parts[0]
    if len(parts) == 2:
        return parts[0], parts[1]
    raise ValueError(f"unexpected object name {obj!r}")


def _objects(stream: Mapping[str, Any]) -> Iterable[str] | None:
    """The stream's target objects, or None when they are only known at run time."""
    template: str = stream["object"]
    out: list[str] = []
    for m in stream.get("members", []):
        if m.get("object"):
            out.append(m["object"])
        elif "{{" not in template:
            out.append(template)
        elif m.get("pattern"):
            return None
        else:
            rendered = _MEMBER_VAR.sub(lambda g, m=m: str(m.get(g.group(1)) or ""), template)
            if "{{" in rendered:
                return None
            out.append(rendered)
    return dict.fromkeys(out) if out else None


def tables(
    plan: Mapping[str, Any],
    connections: Iterable[str] = (),
    warn: Callable[[str], None] = lambda _: None,
) -> list[Table]:
    """Every table a stream writes to a `duckdb` target (optionally only the named connections)."""
    wanted = set(connections)
    out: dict[tuple[str, str], Table] = {}
    for r in plan["replications"]:
        hops: list[Mapping[str, Any]] = r.get("hops") or []
        for s in r["streams"]:
            if s.get("role") == "feed_only":
                continue
            hop = int(s.get("hop", 0))
            target: Mapping[str, Any] = hops[hop]["target"] if hop < len(hops) else r["target"]
            if target["type"] != "duckdb" or (wanted and target["name"] not in wanted):
                continue
            objects = _objects(s)
            if objects is None:
                warn(f"{s['id']}: target object {s['object']!r} is only known at run time; skipped")
                continue
            for obj in objects:
                schema, name = _split(obj)
                key = (schema.lower(), name.lower())
                if key in out:
                    warn(f"{s['id']}: {schema}.{name} is also written by {out[key].stream}")
                    continue
                out[key] = Table(
                    schema=schema,
                    name=name,
                    replication=r["name"],
                    stream=s["id"],
                    asset_key=s["asset"]["key"],
                    mode=s["mode"],
                    description=s["asset"].get("description"),
                )
    return list(out.values())


def render(ts: Iterable[Table], *, prefix: str = "", database: str | None = None) -> str:
    by_schema: dict[str, list[Table]] = {}
    for t in ts:
        by_schema.setdefault(t.schema, []).append(t)
    sources: list[dict[str, Any]] = []
    for schema in sorted(by_schema):
        src: dict[str, Any] = {"name": f"{prefix}{schema}"}
        if database:
            src["database"] = database
        src["schema"] = schema
        src["tables"] = [
            {
                "name": t.name,
                **({"description": t.description} if t.description else {}),
                "meta": {
                    "atlatl": {
                        "replication": t.replication,
                        "stream": t.stream,
                        "asset_key": t.asset_key,
                        "mode": t.mode,
                    }
                },
            }
            for t in sorted(by_schema[schema], key=lambda t: t.name)
        ]
        sources.append(src)
    body = yaml.safe_dump({"version": 2, "sources": sources}, sort_keys=False, width=100)
    return HEADER + body
