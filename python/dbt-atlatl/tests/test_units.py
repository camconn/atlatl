from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
import yaml

from dbt_atlatl._run import AtlatlRunError, RunConfig, command
from dbt_atlatl._sources import render, tables


def stream(sid: str, obj: str, members: list[dict[str, Any]], **kw: Any) -> dict[str, Any]:
    return {
        "id": sid,
        "mode": "incremental",
        "object": obj,
        "members": members,
        "asset": {"key": f"br/{sid}", "description": kw.pop("description", None)},
        **kw,
    }


def member(name: str, **kw: Any) -> dict[str, Any]:
    return {"name": name, "schema": None, "table": None, "pattern": False, "object": None, **kw}


def plan(*replications: dict[str, Any]) -> dict[str, Any]:
    return {"replications": list(replications)}


def repl(name: str, target: str, streams: list[dict[str, Any]], **kw: Any) -> dict[str, Any]:
    return {
        "name": name,
        "target": {"name": target, "type": kw.pop("type", "duckdb")},
        "streams": streams,
        **kw,
    }


def test_tables_resolve_objects() -> None:
    p = plan(
        repl(
            "snap",
            "wh",
            [
                stream("s/symbols", "br.symbols", [member("symbols")], description="Symbols"),
                stream("s/one", "one", [member("one")]),
                stream("s/three", "wh.au.three", [member("three")]),
                stream(
                    "s/tmpl",
                    "br_{{ member.schema }}.{{member.table}}",
                    [member("a.x", schema="a", table="x"), member("b.y", schema="b", table="y")],
                ),
                stream(
                    "s/explicit", "ignored.{{ member.table }}", [member("m", object="br.explicit")]
                ),
            ],
        )
    )
    got = {(t.schema, t.name, t.stream) for t in tables(p)}
    assert got == {
        ("br", "symbols", "s/symbols"),
        ("main", "one", "s/one"),
        ("au", "three", "s/three"),
        ("br_a", "x", "s/tmpl"),
        ("br_b", "y", "s/tmpl"),
        ("br", "explicit", "s/explicit"),
    }


def test_tables_skip_non_duckdb_feed_only_and_runtime_objects() -> None:
    warnings: list[str] = []
    p = plan(
        repl("lake", "lake", [stream("l/a", "br.a", [member("a")])], type="ducklake"),
        repl(
            "wh",
            "wh",
            [
                stream("w/feed", "br.feed", [member("feed")], role="feed_only"),
                stream("w/glob", "br.{{ member.table }}", [member("x.*", pattern=True)]),
                stream("w/dup", "br.a", [member("a")]),
                stream("w/dup2", "BR.A", [member("a")]),
            ],
        ),
        repl("other", "wh2", [stream("o/b", "br.b", [member("b")])]),
    )
    got = [(t.schema, t.name) for t in tables(p, ["wh"], warnings.append)]
    assert got == [("br", "a")]
    assert any("w/glob" in w and "run time" in w for w in warnings)
    assert any("w/dup2" in w and "w/dup" in w for w in warnings)


def test_tables_use_the_hop_target() -> None:
    p = plan(
        repl(
            "chain",
            "lake",
            [
                stream("c/raw", "br.raw", [member("raw")]),
                stream("c/out", "au.out", [member("out")], hop=1),
            ],
            type="ducklake",
            hops=[
                {"hop": 0, "source": {}, "target": {"name": "lake", "type": "ducklake"}},
                {"hop": 1, "source": {}, "target": {"name": "wh", "type": "duckdb"}},
            ],
        )
    )
    assert [(t.schema, t.name) for t in tables(p)] == [("au", "out")]


def test_render() -> None:
    p = plan(
        repl(
            "snap",
            "wh",
            [
                stream("s/z", "br.z", [member("z")], description="Zed"),
                stream("s/a", "br.a", [member("a")]),
                stream("s/m", "au.m", [member("m")]),
            ],
        )
    )
    text = render(tables(p), prefix="atlatl_", database="warehouse")
    assert text.startswith("# Generated by")
    doc = yaml.safe_load(text)
    assert doc["version"] == 2
    assert [(s["name"], s["database"], s["schema"]) for s in doc["sources"]] == [
        ("atlatl_au", "warehouse", "au"),
        ("atlatl_br", "warehouse", "br"),
    ]
    br = doc["sources"][1]["tables"]
    assert [t["name"] for t in br] == ["a", "z"]
    assert br[1]["description"] == "Zed"
    assert br[0]["meta"]["atlatl"] == {
        "replication": "snap",
        "stream": "s/a",
        "asset_key": "br/s/a",
        "mode": "incremental",
    }


def test_run_config(tmp_path: Path) -> None:
    cfg = RunConfig.from_plugin_config(
        {
            "project": "atlatl",
            "env": "dev",
            "replications": "snap",
            "streams": ["a", "b"],
            "vars": {"since": 2024},
            "concurrency": 3,
            "timeout": "10m",
            # dbt-duckdb merges the profile's settings in.
            "memory_limit": "10GB",
        },
        tmp_path,
    )
    assert cfg.project == tmp_path / "atlatl"
    assert cfg.replications == ("snap",)
    assert cfg.commands == ("build", "run")
    assert cfg.vars == {"since": "2024"}


@pytest.mark.parametrize(
    ("config", "msg"),
    [
        ({}, "needs `project`"),
        ({"project": "p", "streams": [1]}, "`streams`"),
        ({"project": "p", "vars": ["x"]}, "`vars`"),
        ({"project": "p", "concurrency": "2"}, "`concurrency`"),
        ({"project": "p", "env": 1}, "`env`"),
    ],
)
def test_run_config_rejects(tmp_path: Path, config: dict[str, Any], msg: str) -> None:
    with pytest.raises(AtlatlRunError, match=msg):
        RunConfig.from_plugin_config(config, tmp_path)


def test_command(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    exe = tmp_path / "atlatl"
    exe.write_text("")
    monkeypatch.setenv("ATLATL_BIN", str(exe))
    cfg = RunConfig.from_plugin_config(
        {
            "project": "p",
            "env": "prod",
            "replications": ["a"],
            "tags": ["t"],
            "vars": {"k": "v"},
            "concurrency": 1,
        },
        tmp_path,
    )
    cmd = command(cfg, tmp_path / "r.json")
    assert cmd[:4] == [str(exe), "--project", str(tmp_path / "p"), "--log-format"]
    joined = " ".join(cmd)
    for part in (
        "run --report",
        "--env prod",
        "--replication a",
        "--tag t",
        "--var k=v",
        "--concurrency 1",
    ):
        assert part in joined


