def test_a_failing_log_stops_atlatl(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    import os
    import signal
    import time

    from dbt_atlatl._run import run

    pidfile = tmp_path / "pid"
    exe = tmp_path / "atlatl"
    exe.write_text(
        "#!/bin/sh\n"
        f"echo $$ > {pidfile}\n"
        "echo started >&2\n"
        "trap 'exit 143' TERM\n"
        "while :; do sleep 0.1; done\n"
    )
    exe.chmod(0o755)
    monkeypatch.setenv("ATLATL_BIN", str(exe))

    def log(line: str) -> None:
        if line == "started":
            raise KeyboardInterrupt

    cfg = RunConfig.from_plugin_config({"project": "p"}, tmp_path)
    started = time.monotonic()
    with pytest.raises(KeyboardInterrupt):
        run(cfg, tmp_path / "wh.duckdb", log)
    assert time.monotonic() - started < 5, "failed fast instead of waiting for atlatl"
    pid = int(pidfile.read_text())
    with pytest.raises(ProcessLookupError):
        os.kill(pid, signal.SIGCONT)
